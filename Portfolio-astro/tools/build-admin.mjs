// Prepares the content editor: copies its script from node_modules into the site (the strict
// Content-Security-Policy blocks CDNs) and writes the small start-up files that point its sign-in
// at this site's own /api/oauth endpoints. The address comes from services.config.json (siteUrl).
import { copyFileSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
const dir = "public/Photography-Studio/admin";
mkdirSync(dir, { recursive: true });
copyFileSync("node_modules/decap-cms/dist/decap-cms.js", `${dir}/decap-cms.js`);
const cfg = JSON.parse(readFileSync("services.config.json", "utf8"));
const site = ((cfg.useCustomDomain && cfg.customDomain) || cfg.siteUrl || "").replace(/\/$/, "");
if (!/^https:\/\/[^/]+$/.test(site)) throw new Error("services.config.json: siteUrl must be an https address");
writeFileSync(`${dir}/boot.js`, "// generated by tools/build-admin.mjs\nwindow.CMS_MANUAL_INIT = true;\n");
writeFileSync(`${dir}/init.js`, `// generated by tools/build-admin.mjs\nCMS.init({ config: { backend: { base_url: ${JSON.stringify(site)}, auth_endpoint: "api/oauth/auth" } } });\n`);
console.log(`admin ok: editor script copied, sign-in via ${site}/api/oauth/auth`);
