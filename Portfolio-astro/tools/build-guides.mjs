#!/usr/bin/env node
// Writes the Travel Advisor's destination pages from its data:
//   public/travel-advisor/destinations/index.html        (all destinations)
//   public/travel-advisor/destinations/<slug>/index.html (one guide each)
// Each page is a thin shell: <title>, description, and the component tags.
// The guide content itself renders from js/destinations.js in the browser.
// Runs automatically before `npm run build` (the "prebuild" script).
import { mkdir, writeFile, readFile, readdir, rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "public", "travel-advisor");
const { content } = await import(join(root, "js", "data.js"));
const { site, destinations, destinationOrder, notes } = content;

// Link previews need absolute image URLs, so they use the site's origin
// from the Netlify build environment. With none (a local build) the og tags
// are skipped rather than pointing at the wrong place.
const origin = (process.env.DEPLOY_PRIME_URL || process.env.URL || "").replace(/\/$/, "");

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

function ogTags({ title, description, path, image }) {
  if (!origin) return "";
  const url = origin + site.base + path;
  const img = origin + site.base + image;
  return [
    `<link rel="canonical" href="${esc(url)}" />`,
    `<meta property="og:type" content="website" />`,
    `<meta property="og:site_name" content="${esc(site.name)}" />`,
    `<meta property="og:title" content="${esc(title)}" />`,
    `<meta property="og:description" content="${esc(description)}" />`,
    `<meta property="og:url" content="${esc(url)}" />`,
    `<meta property="og:image" content="${esc(img)}" />`,
    `<meta property="og:image:width" content="1200" />`,
    `<meta property="og:image:height" content="630" />`,
    `<meta name="twitter:card" content="summary_large_image" />`,
    `<meta name="twitter:title" content="${esc(title)}" />`,
    `<meta name="twitter:description" content="${esc(description)}" />`,
    `<meta name="twitter:image" content="${esc(img)}" />`,
  ].join("\n  ");
}

function page({ depth, title, description, themeColor, main, path, image = "img/og/home.jpg" }) {
  const up = "../".repeat(depth);
  return `<!DOCTYPE html>
<!-- Generated by tools/build-guides.mjs from js/data.js. Edit the data, not this file. -->
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <meta name="description" content="${esc(description)}" />
  <meta name="robots" content="index, follow" />
  <meta name="theme-color" content="${esc(themeColor)}" />
  ${ogTags({ title, description, path, image })}
  <link rel="icon" href="${up}img/favicon.svg" type="image/svg+xml" />
  <link rel="preload" href="${up}fonts/bricolage-grotesque.woff2" as="font" type="font/woff2" crossorigin />
  <link rel="stylesheet" href="${up}css/style.css" />
  <script type="module" src="${up}js/main.js"></script>
  <title>${esc(title)}</title>
</head>
<body>
  <a class="skip-link" href="#main">Skip to content</a>
  <gta-header data-from="site"></gta-header>
  <main id="main">
${main}
  </main>
  <gta-footer data-from="site"></gta-footer>
</body>
</html>
`;
}

const outDir = join(root, "destinations");
// Remove guides for destinations that no longer exist in the data.
const existing = await readdir(outDir, { withFileTypes: true }).catch(() => []);
for (const entry of existing) {
  if (entry.isDirectory() && !destinations[entry.name]) await rm(join(outDir, entry.name), { recursive: true });
}

await mkdir(outDir, { recursive: true });
await writeFile(
  join(outDir, "index.html"),
  page({
    depth: 1,
    title: `Destinations | ${site.name}`,
    description: `Travel guides to ${destinationOrder.map((s) => destinations[s].name).join(", ")}.`,
    themeColor: "#14262E",
    path: "destinations/",
    main: `    <section class="page-head">
      <h1>Destinations</h1>
      <p>Guides to the places Gredin plans trips to most: when to go, where to stay, how to get around, and a sample plan for each.</p>
    </section>
    <section class="pills-row">
      <gta-pills data-from="destinationOrder"></gta-pills>
    </section>
    <section class="when">
      <div class="section-head">
        <h2>Where to go in&hellip;</h2>
        <p>Pick a month to see which guides are in season.</p>
      </div>
      <gta-months data-from="destinationOrder"></gta-months>
    </section>
    <section class="regions">
      <gta-destination-grid data-from="destinationOrder" grouped></gta-destination-grid>
    </section>`,
  })
);

for (const slug of destinationOrder) {
  const d = destinations[slug];
  const dir = join(outDir, slug);
  await mkdir(dir, { recursive: true });
  await writeFile(
    join(dir, "index.html"),
    page({
      depth: 2,
      title: `${d.name} travel guide | ${site.name}`,
      description: d.summary,
      themeColor: d.accent,
      path: `destinations/${slug}/`,
      image: `img/og/${slug}.jpg`,
      main: `    <gta-guide data-from="destinations.${slug}" data-slug="${slug}"></gta-guide>
    <noscript><h1>${esc(d.name)}</h1><p>${esc(d.intro)}</p></noscript>`,
    })
  );
}

// Field notes: an index and one page per note.
const notesDir = join(root, "field-notes");
const noteExisting = await readdir(notesDir, { withFileTypes: true }).catch(() => []);
for (const entry of noteExisting) {
  if (entry.isDirectory() && !notes.some((n) => n.slug === entry.name)) await rm(join(notesDir, entry.name), { recursive: true });
}
await mkdir(notesDir, { recursive: true });
await writeFile(
  join(notesDir, "index.html"),
  page({
    depth: 1,
    title: `Field notes | ${site.name}`,
    description: "Short, checked notes on getting around: tickets, trains, and taxis.",
    themeColor: "#14262E",
    path: "field-notes/",
    main: `    <section class="page-head">
      <h1>Field notes</h1>
      <p>Short notes on the practical parts of a trip: what to book ahead, how to get from the airport, what a ride costs.</p>
    </section>
    <section class="notes-section">
      <gta-notes data-from="notes"></gta-notes>
    </section>`,
  })
);
for (const [i, n] of notes.entries()) {
  const dir = join(notesDir, n.slug);
  await mkdir(dir, { recursive: true });
  await writeFile(
    join(dir, "index.html"),
    page({
      depth: 2,
      title: `${n.title} | ${site.name}`,
      description: n.summary,
      themeColor: "#14262E",
      path: `field-notes/${n.slug}/`,
      image: `img/og/${n.guide}.jpg`,
      main: `    <gta-note data-from="notes.${i}"></gta-note>
    <noscript><h1>${esc(n.title)}</h1><p>${esc(n.summary)}</p></noscript>`,
    })
  );
}

// Travel essentials (packing and choosing an airline).
await mkdir(join(root, "packing"), { recursive: true });
await writeFile(
  join(root, "packing", "index.html"),
  page({
    depth: 1,
    title: `Travel essentials | ${site.name}`,
    description: "What to pack, how to handle money and data, and how to choose an airline.",
    themeColor: "#14262E",
    path: "packing/",
    main: `    <section class="page-head">
      <h1>Travel essentials</h1>
      <p>What to pack and how to choose a flight, for every guide on this site.</p>
    </section>
    <section class="essentials">
      <gta-essentials data-from="essentials"></gta-essentials>
    </section>`,
  })
);

// Keep the hand-written home page's link-preview tags in step.
const homePath = join(root, "index.html");
const home = await readFile(homePath, "utf8");
const homeTags = ogTags({ title: `${site.name} | Trips planned by a person`, description: "Gredin Travel Advisor plans your trip day by day, books it, and stays on call while you travel.", path: "", image: "img/og/home.jpg" });
const nextHome = home.replace(/<!-- og:start -->[\s\S]*?<!-- og:end -->/, `<!-- og:start -->\n  ${homeTags}\n  <!-- og:end -->`);
if (nextHome !== home) await writeFile(homePath, nextHome);

console.log(`build-guides: wrote destinations index, ${destinationOrder.length} guides, ${notes.length} field notes`);
